# ----------------------------------------------------------------------------- script sheet

def write_script(site: str) -> Path:
    story = C.load_story(site)
    segs = C.expand_story(story)
    titles = {ch["id"]: ch for ch in story.get("chapters") or []}
    lines = [
        f"# Voice script: {story.get('title', site)}",
        "",
        f"Site: `{site}`. Generated by `python tools/play/voice/render.py --script-only` from",
        f"`content/play/{site}/story.json`. Do not edit by hand. {len(segs)} clips,",
        f"{sum(s['words'] for s in segs)} words.",
        "",
        "## How to read",
        "",
        "- One file per row, named `<clip id>.m4a` (or `.wav` for conversion), mono.",
        "- Read only the Line column. Never read the options or the interface.",
        "- Do not add silence. Leave about 40 ms at the head and tail. The game inserts the pause after each clip.",
        "- One narrator, calm and unhurried. Sentences end downward. A witness's words are read in the same voice.",
        "- Pace: steady is about 150 words a minute, slow about 125, brisk about 170 (lists only).",
        "  The Seconds column is the clip length that pace gives. Lines of 1 to 3 words have no target: do not rush them.",
        "- Pause after: breath 250 ms, beat 600 ms, hold 1,100 ms, silence 1,800 to 2,500 ms. Shown for context, not recorded.",
        "",
        "## Names",
        "",
        "| Name | Intended |",
        "|---|---|",
    ]
    for e in C.load_lexicon()["entries"]:
        lines.append(f"| {e['name']} | {e['intended']} |")
    current = None
    n = 0
    for s in segs:
        if s["chapter"] != current:
            current = s["chapter"]
            ch = titles.get(current, {})
            lines += ["", f"## {ch.get('title', current)} (`{current}`)", "",
                      "| # | Clip id | Pace | Seconds | Pause after (ms) | Context | Line |",
                      "|---|---|---|---|---|---|---|"]
        n += 1
        if s["words"] <= C.EXEMPT_MAX_WORDS:
            secs = "free"
        else:
            secs = f"{s['words'] * 60 / C.PACE_WPM[s['pace']]:.1f}"
        context = []
        if s["role"]:
            context.append(s["role"])
        if s["parent"]:
            context.append(f"after the player picks {s['parent']}")
        elif s["type"] not in ("line",):
            context.append(s["type"])
        lines.append(f"| {n} | `{s['id']}` | {s['pace']} | {secs} | {s['pause_after_ms']} | {', '.join(context)} | {s['text']} |")
    out = C.HERE / "voice_script.md"
    out.write_text("\n".join(lines) + "\n", encoding="utf-8")
    return out


# ----------------------------------------------------------------------------- engine worker

class Worker:
    def __init__(self, voice: str, cfg: dict):
        py = C.venv_python(cfg.get("venv", ".venv"))
        if not py.exists():
            sys.exit(f"Voice {voice!r} needs the environment {py.parents[1]}. See README.md (Setup).")
        args = [a.replace("{models}", str(C.MODELS)) for a in cfg.get("args", [])]
        (C.SCRATCH / "logs").mkdir(parents=True, exist_ok=True)
        self.log = open(C.SCRATCH / "logs" / f"worker-{voice}.log", "w", encoding="utf-8")
        self.p = subprocess.Popen([str(py), str(C.HERE / cfg["worker"]), *args], stdin=subprocess.PIPE,
                                  stdout=subprocess.PIPE, stderr=self.log, env=C.cpu_only_env(),
                                  encoding="utf-8", bufsize=1)
        ready = self._read()
        if not ready.get("ready"):
            sys.exit(f"Engine failed to start: {ready.get('error')}")
        if ready.get("device") != "cpu":
            sys.exit("Engine did not report CPU. Refusing to continue.")
        self.info = ready

    def _read(self) -> dict:
        line = self.p.stdout.readline()
        if not line:
            raise RuntimeError(f"Engine worker stopped. See {self.log.name}")
        return json.loads(line)

    def synth(self, **req) -> dict:
        self.p.stdin.write(json.dumps(req, ensure_ascii=False) + "\n")
        self.p.stdin.flush()
        res = self._read()
        if not res.get("ok"):
            raise RuntimeError(res.get("error"))
        return res

    def close(self):
        try:
            self.p.stdin.write('{"cmd": "quit"}\n')
            self.p.stdin.flush()
            self.p.wait(timeout=30)
        except Exception:
            self.p.kill()
        self.log.close()


class LazyWorker:
    """Starts the engine the first time a clip really has to be read."""

    def __init__(self, voice: str, cfg: dict):
        self.voice, self.cfg, self._w = voice, cfg, None

    def synth(self, **req) -> dict:
        if self._w is None:
            print("Starting engine...")
            self._w = Worker(self.voice, self.cfg)
        return self._w.synth(**req)

    def close(self):
        if self._w is not None:
            self._w.close()


def update_voice_index(site: str, default: str | None = None) -> Path:
    """audio/voices.json: the list of voice folders the player reads (lib/play/audio.js).

    Rebuilt from the manifests after every render. "default" is the voice the player starts
    with: the one named with --make-default, else the one already chosen, else the voice
    with the most clips.
    """
    root = C.audio_dir(site, "_").parent
    path = root / "voices.json"
    old = {}
    if path.exists():
        try:
            old = json.loads(path.read_text(encoding="utf-8"))
        except ValueError:
            old = {}
    voices = []
    for d in sorted(root.iterdir()) if root.exists() else []:
        m = d / "manifest.json"
        if not (d.is_dir() and m.exists()):
            continue
        man = json.loads(m.read_text(encoding="utf-8"))
        chapters = list(dict.fromkeys(c.get("chapter") for c in man.get("clips", []) if c.get("chapter")))
        voices.append({"id": d.name, "clips": len(man.get("clips", [])), "chapters": chapters,
                       "engine": man.get("engine"), "language": man.get("language"),
                       "names_reel": (d / "_names_reel.m4a").exists()})
    ids = [v["id"] for v in voices]
    chosen = default or (old.get("default") if isinstance(old, dict) else None)
    if chosen not in ids:
        chosen = max(voices, key=lambda v: v["clips"])["id"] if voices else None
    path.write_text(json.dumps({"voices": voices, "default": chosen, "credit": "Narration: synthetic voice."},
                               indent=2, ensure_ascii=False) + "\n", encoding="utf-8")
    return path


# ----------------------------------------------------------------------------- audio steps

def load_raw(path: Path):
    """Engine output -> mono float64 at 44.1 kHz, plus the raw sample peak in dBFS."""
    import numpy as np
    import soundfile as sf
    from math import gcd
    from scipy.signal import resample_poly
    x, sr = sf.read(str(path), dtype="float64", always_2d=True)
    x = x.mean(axis=1)
    raw_peak = C.sample_peak_db(x)
    if sr != C.SR:
        g = gcd(C.SR, sr)
        x = resample_poly(x, C.SR // g, sr // g)
    return np.asarray(x, dtype=np.float64), raw_peak


def cut_speech(x):
    """Keep the speech with a 10 ms margin at each end."""
    s, e = C.speech_bounds(x, C.SR)
    m = int(C.SR * 0.010)
    return x[max(0, s - m):min(len(x), e + m)]


def atempo(x, tempo: float, tmp: Path):
    """Time-stretch without changing pitch (ffmpeg atempo). tempo > 1 is faster."""
    import soundfile as sf
    a, b = tmp.with_suffix(".in.wav"), tmp.with_suffix(".out.wav")
    sf.write(str(a), x, C.SR, subtype="FLOAT")
    C.run(["ffmpeg", "-y", "-v", "error", "-i", str(a), "-filter:a", f"atempo={tempo:.5f}",
           "-ar", str(C.SR), "-ac", "1", "-c:a", "pcm_f32le", str(b)])
    y, _ = sf.read(str(b), dtype="float64")
    a.unlink(missing_ok=True)
    b.unlink(missing_ok=True)
    return y


def fade(x):
    import numpy as np
    n = int(C.SR * C.FADE_MS / 1000)
    if len(x) < 2 * n:
        return x
    ramp = 0.5 - 0.5 * np.cos(np.linspace(0, np.pi, n))
    y = x.copy()
    y[:n] *= ramp
    y[-n:] *= ramp[::-1]
    return y


def pad(x, ms: float = C.EDGE_SILENCE_MS - 10):
    """Digital silence at each end. With the 10 ms speech margin this gives about 40 ms."""
    import numpy as np
    z = np.zeros(int(C.SR * ms / 1000))
    return np.concatenate([z, x, z])


def limit(x, ceiling_db: float):
    """Look-ahead peak limiter: 3 ms hold, 3 ms smoothing. Returns (audio, max reduction in dB)."""
    import numpy as np
    from scipy.ndimage import minimum_filter1d, uniform_filter1d
    if C.true_peak_db(x) <= ceiling_db:
        return x, 0.0
    ceiling = 10 ** (ceiling_db / 20) * 0.97
    need = np.minimum(1.0, ceiling / np.maximum(np.abs(x), 1e-9))
    win = int(C.SR * 0.003) | 1
    g = uniform_filter1d(minimum_filter1d(need, size=win, mode="nearest"), size=win, mode="nearest")
    y = x * g
    over = C.true_peak_db(y) - ceiling_db
    if over > 0:
        y = y * 10 ** (-over / 20)
    return y, round(-C.db(float(g.min())), 2)


def normalise(x):
    """Loudness to TARGET_LUFS, then the peak ceiling. Returns (audio, info).

    Limiting a peak lowers the loudness a little, so gain and limiter are applied up to
    four times until the result is within 0.1 LU of the target.
    """
    y = x
    reduced = 0.0
    method = "bs1770"
    for _ in range(4):
        lufs, method = C.loudness(y, C.SR)
        if abs(lufs - C.TARGET_LUFS) <= 0.1 and C.true_peak_db(y) <= C.PRE_ENCODE_PEAK_DB:
            break
        y = y * 10 ** ((C.TARGET_LUFS - lufs) / 20)
        y, r = limit(y, C.PRE_ENCODE_PEAK_DB)
        reduced += r
    return y, {"loudness_method": method, "limiter_db": round(reduced, 2)}


def encode(x, out: Path, tmp: Path):
    import soundfile as sf
    wav = tmp.with_suffix(".final.wav")
    sf.write(str(wav), x, C.SR, subtype="PCM_24")
    out.parent.mkdir(parents=True, exist_ok=True)
    C.run(["ffmpeg", "-y", "-v", "error", "-i", str(wav), "-c:a", "aac", "-b:a", "96k", "-ar", str(C.SR),
           "-ac", "1", "-movflags", "+faststart", "-map_metadata", "-1", str(out)])
    wav.unlink(missing_ok=True)


MAX_PASSES = 5
MAX_RETRIES = 3


def next_speed(tried: list[tuple[float, float]], target_ms: float) -> float:
    """Next engine speed to try, from the (speed, speech ms) pairs measured so far.

    Length is roughly proportional to 1 / speed, so interpolate in 1 / speed between the
    closest reading that was too long and the closest that was too short. With readings on
    one side only, scale from the nearest one.
    """
    longer = [t for t in tried if t[1] >= target_ms]
    shorter = [t for t in tried if t[1] < target_ms]
    if longer and shorter:
        a = min(longer, key=lambda t: t[1] - target_ms)
        b = min(shorter, key=lambda t: target_ms - t[1])
        ia, ib = 1 / a[0], 1 / b[0]
        if a[1] != b[1] and ia != ib:
            return 1 / (ib + (target_ms - b[1]) * (ia - ib) / (a[1] - b[1]))
    s, ms = min(tried, key=lambda t: abs(t[1] - target_ms))
    return s * ms / target_ms


def clip_key(seg: dict, tts_text: str, extras: dict, cfg: dict, salt: int = 0) -> str:
    base = {k: v for k, v in cfg.items() if k != "clip_overrides"}
    parts = [PIPELINE_VERSION, seg["text"], tts_text, extras, seg["pace"], base, salt]
    override = (cfg.get("clip_overrides") or {}).get(seg["id"])
    if override:
        parts.append(override)
    blob = json.dumps(parts, sort_keys=True, ensure_ascii=False)
    return hashlib.sha1(blob.encode("utf-8")).hexdigest()[:16]


def render_clip(worker: Worker, voice: str, cfg: dict, seg: dict, lexicon: dict, out: Path, key: str,
                tts_text: str, extras: dict, salt: int = 0) -> tuple[dict, dict]:
    """Synthesise one segment and bring it to its pace. Returns (manifest entry, debug log)."""
    tmp_dir = C.SCRATCH / "raw" / voice
    tmp_dir.mkdir(parents=True, exist_ok=True)
    tmp = tmp_dir / seg["id"]
    speeds = cfg["speed"]
    words, pace = seg["words"], seg["pace"]
    exempt = words <= C.EXEMPT_MAX_WORDS
    target_ms = words * 60000.0 / C.PACE_WPM[pace]
    edge_ms = 2 * (C.EDGE_SILENCE_MS - 10)
    speech_target_ms = max(target_ms - edge_ms, 100.0)
    seed = (zlib.crc32(seg["id"].encode("utf-8")) + salt) % (2 ** 31)

    # Exempt clips (1 to 3 words) are read once at the voice's usual speed for that pace,
    # never above the engine's own rate, and never time-stretched. The others are measured
    # and re-read until they fit. No clip goes below speeds["min"]: under that speed the
    # round trip gets worse for this voice (see calibrate.py).
    floor = speeds.get("min_short", speeds["min"]) if exempt else speeds["min"]
    override = (cfg.get("clip_overrides") or {}).get(seg["id"]) or {}
    floor = override.get("min", floor)              # a clip that failed its round trip at the usual floor
    speed = min(max(speeds[pace], floor), speeds["max"])
    if exempt:
        speed = min(speed, 1.0)
    passes = []
    tried: list[tuple[float, float]] = []
    best = None
    for _ in range(MAX_PASSES):
        raw = tmp.with_suffix(".raw.wav")
        res = worker.synth(text=tts_text, speed=round(speed, 4), out=str(raw), seed=seed, **extras)
        x, raw_peak = load_raw(raw)
        speech = cut_speech(x)
        ms = len(speech) / C.SR * 1000
        ratio = ms / speech_target_ms               # > 1: too slow
        tried.append((speed, ms))
        passes.append({"speed": round(speed, 4), "speech_ms": round(ms, 1), "ratio": round(ratio, 4)})
        cand = {"speech": speech, "speed": speed, "ratio": ratio, "raw_peak": raw_peak, "res": res}
        if best is None or abs(ratio - 1) < abs(best["ratio"] - 1):
            best = cand
        if exempt or abs(ratio - 1) <= 0.03:
            break
        nxt = min(max(next_speed(tried, speech_target_ms), floor), speeds["max"])
        if any(abs(nxt - s) < 0.008 for s, _ in tried):
            break
        speed = nxt
    speech, ratio = best["speech"], best["ratio"]

    tempo = 1.0
    if not exempt and abs(ratio - 1) > 0.02:
        tempo = min(max(ratio, C.ATEMPO_MIN), C.ATEMPO_MAX)
        speech = cut_speech(pad(atempo(speech, tempo, tmp), 20))

    final, norm = normalise(pad(fade(speech)))
    encode(final, out, tmp)

    y = C.decode(out)
    duration_ms = round(len(y) / C.SR * 1000)
    lufs, _ = C.loudness(y, C.SR)
    measured = C.wpm(words, duration_ms)
    entry = {
        "id": seg["id"],
        "chapter": seg["chapter"],
        "file": out.name,
        "text": seg["text"],
        "pace": pace,
        "pause_after_ms": seg["pause_after_ms"],
        "duration_ms": duration_ms,
        "words": words,
        "wpm": measured,
        "wpm_target": C.PACE_WPM[pace],
        "pace_exempt": exempt,
        "pace_ok": C.pace_ok(words, pace, measured),
        "engine_speed": round(best["speed"], 3),
        "atempo": round(tempo, 3),
        "loudness_lufs": round(lufs, 2),
        "loudness_method": norm["loudness_method"],
        "true_peak_db": round(C.true_peak_db(y), 2),
        "limiter_db": norm["limiter_db"],
        "raw_peak_db": round(best["raw_peak"], 2),
        "seed_salt": salt,
        "key": key,
    }
    debug = {"id": seg["id"], "tts_text": tts_text, "extras": extras, "phonemes": best["res"].get("phonemes"),
             "passes": passes}
    return entry, debug


