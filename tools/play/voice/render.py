def render_names_reel(worker: Worker, voice: str, cfg: dict, lexicon: dict, site: str) -> Path:
    import numpy as np
    tmp_dir = C.SCRATCH / "raw" / voice
    tmp_dir.mkdir(parents=True, exist_ok=True)
    gap = np.zeros(int(C.SR * REEL_GAP_MS / 1000))
    parts, rows = [], []
    cursor = int(C.SR * C.EDGE_SILENCE_MS / 1000)
    parts.append(np.zeros(cursor))
    names = C.lexicon_names(lexicon)
    sp = cfg["speed"]
    reel_speed = min(max(sp["steady"], sp.get("min_short", sp["min"])), 1.0)   # as for any clip of 1 to 3 words
    for i, name in enumerate(names):
        tts_text, extras = C.apply_lexicon(name + ".", lexicon, cfg["engine"], cfg.get("variant"))
        raw = tmp_dir / f"_name_{i:02d}.raw.wav"
        res = worker.synth(text=tts_text, speed=reel_speed, out=str(raw),
                           seed=zlib.crc32(name.encode("utf-8")), **extras)
        x, _ = load_raw(raw)
        speech = fade(cut_speech(x))
        lufs = C.kw_rms_loudness(speech, C.SR)
        speech = speech * 10 ** ((C.TARGET_LUFS - lufs) / 20)
        speech, _ = limit(speech, C.PRE_ENCODE_PEAK_DB)
        rows.append({"n": i + 1, "name": name, "tts_text": tts_text, "extras": extras,
                     "phonemes": res.get("phonemes"), "start_ms": round(cursor / C.SR * 1000),
                     "end_ms": round((cursor + len(speech)) / C.SR * 1000)})
        parts.append(speech)
        cursor += len(speech)
        if i < len(names) - 1:
            parts.append(gap)
            cursor += len(gap)
        print(f"  name {i + 1:2d}/{len(names)}  {name}")
    parts.append(np.zeros(int(C.SR * C.EDGE_SILENCE_MS / 1000)))
    out = C.audio_dir(site, voice) / "_names_reel.m4a"
    encode(np.concatenate(parts), out, tmp_dir / "_names_reel")
    update_voice_index(site)
    reports = C.HERE / "reports"
    reports.mkdir(exist_ok=True)
    (reports / f"names_{voice}.json").write_text(json.dumps(
        {"voice": voice, "site": site, "gap_ms": REEL_GAP_MS, "file": str(out.relative_to(C.ROOT)).replace("\\", "/"),
         "names": rows}, indent=2, ensure_ascii=False) + "\n", encoding="utf-8")
    write_names_md(lexicon)
    return out


def write_names_md(lexicon: dict) -> Path:
    lines = [
        "# Names reel",
        "",
        "Each candidate voice has one file, `public/play/packs/<site>/v1/audio/<voice>/_names_reel.m4a`,",
        f"saying every lexicon name once, in this order, with {REEL_GAP_MS} ms of silence between names.",
        "Generated by `python tools/play/voice/render.py --voice <name> --names-reel`. Do not edit by hand:",
        "correct `lexicon.json` and render again.",
        "",
        "The Intended column is a best understanding, not checked by ear. `[SAMBIT: listen to the names reel and correct any name.]`",
        "",
        "| # | Name | Intended | Spoken in the story so far |",
        "|---|---|---|---|",
    ]
    for i, e in enumerate(lexicon["entries"], 1):
        lines.append(f"| {i} | {e['name']} | {e['intended']} | {'yes' if e.get('spoken_in_story') else 'no, reel only'} |")
    lines += ["", "## Notes per name", ""]
    for e in lexicon["entries"]:
        lines.append(f"- **{e['name']}**: {e.get('notes', '')}")
    reports = sorted((C.HERE / "reports").glob("names_*.json"))
    for rp in reports:
        data = json.loads(rp.read_text(encoding="utf-8"))
        lines += ["", f"## What `{data['voice']}` was given", "",
                  f"File: `{data['file']}`. Phonemes are what the engine's own text front end produced for the text sent. They are the engine's notation, not a transcription of the audio.", "",
                  "| # | Name | Starts at (ms) | Text sent to the engine | Phonemes the engine used |",
                  "|---|---|---|---|---|"]
        for r in data["names"]:
            extra = ""
            if r.get("extras", {}).get("arpabet"):
                extra = " + dictionary: " + "; ".join(f"{k} = {v}" for k, v in r["extras"]["arpabet"].items())
            lines.append(f"| {r['n']} | {r['name']} | {r['start_ms']} | `{r['tts_text']}`{extra} | `{r.get('phonemes') or ''}` |")
    out = C.HERE / "names_reel.md"
    out.write_text("\n".join(lines) + "\n", encoding="utf-8")
    return out


# ----------------------------------------------------------------------------- main

def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--voice")
    ap.add_argument("--site", default=C.DEFAULT_SITE)
    ap.add_argument("--chapters", help="comma separated chapter ids, default all")
    ap.add_argument("--only", help="comma separated clip ids")
    ap.add_argument("--force", action="store_true", help="render again even if the clip is up to date")
    ap.add_argument("--seed", type=int, help="seed offset for the clips rendered in this run (engines with random sampling: MeloTTS, Piper)")
    ap.add_argument("--retry-failed", action="store_true",
                    help="render again, with the next seed, the clips whose round trip failed in the last check.py report (at most 3 retries per clip)")
    ap.add_argument("--names-reel", action="store_true", help="render only the names reel for this voice")
    ap.add_argument("--make-default", action="store_true", help="make this voice the one the player starts with (audio/voices.json)")
    ap.add_argument("--script-only", action="store_true", help="write voice_script.md and stop")
    ap.add_argument("--list", action="store_true", help="list voices and stop")
    args = ap.parse_args()

    voices = C.load_voices()["voices"]
    if args.list:
        for name, v in voices.items():
            print(f"{name:16s} {v['engine']:7s} {v['engine_voice']:22s} {v['language']:6s} {v['licence']}")
        return 0
    if args.script_only:
        print(f"Wrote {write_script(args.site)}")
        return 0
    if not args.voice:
        ap.error("--voice is required (see --list)")
    if args.voice not in voices:
        ap.error(f"Unknown voice {args.voice!r}. Known: {', '.join(voices)}")
    cfg = voices[args.voice]
    lexicon = C.load_lexicon()

    C.ensure_venv()

    story = C.load_story(args.site)
    all_segs = C.expand_story(story)
    chapters = [c.strip() for c in args.chapters.split(",")] if args.chapters else None
    only = {c.strip() for c in args.only.split(",")} if args.only else None
    retry: set[str] = set()
    if args.retry_failed:
        report = C.HERE / "reports" / f"{args.voice}.json"
        if not report.exists():
            ap.error(f"No report for {args.voice}. Run check.py first.")
        retry = {c["id"] for c in json.loads(report.read_text(encoding="utf-8"))["clips"] if c.get("stt_status") == "fail"}
        if not retry:
            print("No round-trip failures in the last report. Nothing to retry.")
            return 0
        only = retry if only is None else (only & retry)
    if chapters:
        known = {s["chapter"] for s in all_segs}
        missing = [c for c in chapters if c not in known]
        if missing:
            ap.error(f"No spoken lines in chapter(s): {', '.join(missing)}. Known: {', '.join(sorted(known))}")
    if only:
        unknown = only - {s["id"] for s in all_segs}
        if unknown:
            ap.error(f"Unknown clip id(s): {', '.join(sorted(unknown))}")
    todo = [s for s in all_segs if (not chapters or s["chapter"] in chapters) and (not only or s["id"] in only)]

    out_dir = C.audio_dir(args.site, args.voice)
    out_dir.mkdir(parents=True, exist_ok=True)
    manifest_path = out_dir / "manifest.json"
    old = {}
    if manifest_path.exists():
        old = {c["id"]: c for c in json.loads(manifest_path.read_text(encoding="utf-8")).get("clips", [])}

    print(f"Voice {args.voice} ({cfg['engine']} {cfg['engine_voice']}), CPU only.")
    worker = LazyWorker(args.voice, cfg)
    try:
        if args.names_reel:
            print(f"Wrote {render_names_reel(worker, args.voice, cfg, lexicon, args.site)}")
            return 0
        done, debug_rows = {}, []
        for i, seg in enumerate(todo, 1):
            tts_text, extras = C.apply_lexicon(seg["text"], lexicon, cfg["engine"], cfg.get("variant"))
            out = out_dir / f"{seg['id']}.m4a"
            prev = old.get(seg["id"])
            salt = (prev or {}).get("seed_salt", 0)
            if args.seed is not None:
                salt = args.seed
            elif seg["id"] in retry:
                if salt >= MAX_RETRIES:
                    print(f"[{i:2d}/{len(todo)}] {seg['id']:12s} already tried {MAX_RETRIES} other seeds. Left as an open issue.")
                    done[seg["id"]] = prev
                    continue
                salt += 1
            key = clip_key(seg, tts_text, extras, cfg, salt)
            if prev and prev.get("key") == key and out.exists() and not args.force:
                done[seg["id"]] = {**prev, "pause_after_ms": seg["pause_after_ms"], "chapter": seg["chapter"]}
                print(f"[{i:2d}/{len(todo)}] {seg['id']:12s} up to date")
                continue
            entry, debug = render_clip(worker, args.voice, cfg, seg, lexicon, out, key, tts_text, extras, salt)
            done[seg["id"]] = entry
            debug_rows.append(debug)
            flag = "" if entry["pace_ok"] in (True, None) else "  PACE OUT OF RANGE"
            print(f"[{i:2d}/{len(todo)}] {seg['id']:12s} {entry['duration_ms']:5d} ms  {entry['wpm']:6.1f} wpm "
                  f"(target {entry['wpm_target']}{', exempt' if entry['pace_exempt'] else ''})  "
                  f"speed {entry['engine_speed']:.2f} atempo {entry['atempo']:.2f}{flag}")
    finally:
        worker.close()

    # Manifest: every clip of the story that has a file, in play order.
    clips = []
    for seg in all_segs:
        entry = done.get(seg["id"])
        if entry is None:
            prev = old.get(seg["id"])
            if prev and (out_dir / f"{seg['id']}.m4a").exists():
                stale = prev.get("text") != seg["text"] or prev.get("pace") != seg["pace"]
                entry = {**prev, "pause_after_ms": seg["pause_after_ms"], "chapter": seg["chapter"]}
                if stale:
                    entry["stale"] = True
        if entry:
            clips.append(entry)
    manifest = {
        "site": args.site,
        "voice": args.voice,
        "engine": cfg["engine"],
        "engine_voice": cfg["engine_voice"],
        "language": cfg["language"],
        "licence": cfg["licence"],
        "credit": "Narration: synthetic voice.",
        "generated": datetime.date.today().isoformat(),
        "format": {"container": "m4a", "codec": "aac", "channels": 1, "sample_rate": C.SR, "bitrate": "96k"},
        "targets": {"wpm": C.PACE_WPM, "wpm_tolerance": C.PACE_TOLERANCE, "exempt_max_words": C.EXEMPT_MAX_WORDS,
                    "loudness_lufs": C.TARGET_LUFS, "true_peak_max_db": C.TRUE_PEAK_MAX_DB,
                    "edge_silence_ms": C.EDGE_SILENCE_MS},
        "clips": clips,
    }
    manifest_path.write_text(json.dumps(manifest, indent=2, ensure_ascii=False) + "\n", encoding="utf-8")

    if debug_rows:
        log = C.SCRATCH / "logs" / f"render-{args.voice}.json"
        prev_rows = {}
        if log.exists():
            prev_rows = {r["id"]: r for r in json.loads(log.read_text(encoding="utf-8"))}
        prev_rows.update({r["id"]: r for r in debug_rows})
        log.write_text(json.dumps(list(prev_rows.values()), indent=2, ensure_ascii=False), encoding="utf-8")

    index = update_voice_index(args.site, args.voice if args.make_default else None)
    print(f"Voice index: {index}  (default: {json.loads(index.read_text(encoding='utf-8'))['default']})")

    story_ids = {s["id"] for s in all_segs}
    orphans = sorted(p.name for p in out_dir.glob("*.m4a") if p.stem not in story_ids and not p.name.startswith("_"))
    missing = [s["id"] for s in all_segs if not (out_dir / f"{s['id']}.m4a").exists()]
    out_pace = [c["id"] for c in clips if c.get("pace_ok") is False]
    print(f"\nManifest: {manifest_path}  ({len(clips)} clips)")
    if out_pace:
        print(f"Out of pace: {', '.join(out_pace)}")
    if missing:
        print(f"Not yet rendered in this voice: {len(missing)} clips ({', '.join(missing[:6])}{'...' if len(missing) > 6 else ''})")
    if orphans:
        print(f"Files with no line in the story (delete by hand if unwanted): {', '.join(orphans)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
